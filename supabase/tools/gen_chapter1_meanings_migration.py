#!/usr/bin/env python3
"""Generate the migration that sets chapter 1 meanings from content/chapter1_meanings.json.
Run once: python3 supabase/tools/gen_chapter1_meanings_migration.py <timestamp>"""
import json, os, sys

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
CREDIT = ('Sanskrit: moolam via Heritage IITK (public domain). Recitation: Swami Brahmananda, CC BY-SA 4.0, Heritage IITK. '
          'English: Swami Sivananda. Hindi: Swami Tejomayananda. Translations via Heritage IITK with permission. '
          'Title and daily note: AI-drafted. Draft — pending editorial review')
q = lambda s: '$q$' + s + '$q$'
m = json.load(open(os.path.join(ROOT, 'content/chapter1_meanings.json'), encoding='utf-8'))
assert sorted(map(int, m)) == list(range(1, 48))
vals = ',\n'.join('  (%s, %s, %s)' % (v, q(e['en']), q(e['hi'])) for v, e in sorted(m.items(), key=lambda x: int(x[0])))
sql = f"""-- GENERATED by supabase/tools/gen_chapter1_meanings_migration.py from content/chapter1_meanings.json. Do not edit by hand.
-- Chapter 1 meanings: English (Swami Sivananda) and Hindi (Swami Tejomayananda), used with permission from Heritage IITK.
-- Replaces the earlier AI-drafted English paraphrase; titles and daily notes stay AI-drafted.
with m(verse, en, hi) as (values
{vals}
)
update shloks set english_meaning = m.en, hindi_meaning = m.hi, translation_credit = {q(CREDIT)}
from m where shloks.chapter = 1 and shloks.verse = m.verse;
"""
open(os.path.join(ROOT, f'supabase/migrations/{sys.argv[1]}_chapter1_meanings.sql'), 'w', encoding='utf-8').write(sql)
