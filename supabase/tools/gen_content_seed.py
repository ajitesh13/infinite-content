#!/usr/bin/env python3
"""Generate supabase/seed.sql from content/bhagavad-gita-daily-life.md and assets/background/.

Verse text is copied verbatim from the Markdown; nothing is rewritten.
Run from the repo root: python3 supabase/tools/gen_content_seed.py
"""
import re, os

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
BASE = 'https://zsauxjqrtdrjbpanlypq.supabase.co/storage/v1/object/public/reels/backgrounds/'

SECTION_THEMES = {
    'Work, duty and focus': ['duty'],
    'Managing stress, desire and anger': ['equanimity', 'mind'],
    'Self-discipline, empathy and relationships': ['self-mastery', 'mind'],
    'Devotion, character and life purpose': ['faith', 'dharma'],
}
# Draft Hindi meanings from the original dev seed; only for single-verse entries they match exactly.
HINDI = {
    (2, 22): 'जैसे मनुष्य पुराने वस्त्रों को त्यागकर नए वस्त्र धारण करता है, वैसे ही आत्मा पुराने शरीरों को त्यागकर नए शरीरों को प्राप्त होती है।',
    (2, 47): 'तुम्हारा अधिकार केवल कर्म करने में है, उसके फलों में कभी नहीं। इसलिए न फल की इच्छा से कर्म करो और न कर्म न करने में आसक्त हो।',
}

text = open(os.path.join(ROOT, 'content/bhagavad-gita-daily-life.md'), encoding='utf-8').read()
items, sec = [], None
for b in re.split(r'\n(?=##+ )', text):
    if b.startswith('## '):
        sec = b[3:].split('\n')[0].strip(); continue
    m = re.match(r'### Bhagavad Gītā (\d+)\.(\d+)(?:[–-](\d+))? — (.+)', b)
    if not m: continue
    g = lambda k: (re.search(r'\*\*' + k + r':\*\*\s*(.+)', b) or [None, None])[1]
    items.append(dict(chapter=int(m[1]), verse=int(m[2]), verse_end=int(m[3]) if m[3] else None,
                      title=m[4].strip(), section=sec, themes=SECTION_THEMES[sec],
                      sanskrit='\n'.join(l[2:] for l in b.split('\n') if l.startswith('> ')),
                      hindi=HINDI.get((int(m[1]), int(m[2]))) if not m[3] else None,
                      english=g('Meaning'), application=g('Daily application')))
items.sort(key=lambda i: (i['chapter'], i['verse']))

bgs = sorted(f for f in os.listdir(os.path.join(ROOT, 'assets/background')) if f.endswith('.jpg'))
q = lambda s: 'null' if s is None else '$q$' + s + '$q$'
rows = []
for n, i in enumerate(items):
    rows.append('  (%d, %s, %s, %s, %s, %s, %s, %s, \'{%s}\'::text[])' % (
        i['chapter'], i['verse'], i['verse_end'] or 'null', q(i['sanskrit']), q(i['hindi']), q(i['english']),
        q(i['title']), q(i['application']), ','.join(i['themes'])))

sql = f"""-- GENERATED by supabase/tools/gen_content_seed.py from content/bhagavad-gita-daily-life.md. Do not edit by hand.
-- DRAFT text: Sanskrit/meanings not yet scholar-reviewed. Reels are published so they appear in the feed.
-- Backgrounds come from assets/background/ (uploaded to storage bucket reels/backgrounds/).
truncate reels, shloks cascade;

with s as (
  insert into shloks (chapter, verse, verse_end, sanskrit, hindi_meaning, english_meaning, title_english, application_english, themes)
  select chapter, verse, verse_end, sanskrit, hindi_meaning, english_meaning, title_english, application_english, themes
  from (values
""" + ',\n'.join(rows) + f"""
  ) as v(chapter, verse, verse_end, sanskrit, hindi_meaning, english_meaning, title_english, application_english, themes)
  returning id, chapter, verse
), posters(chapter, verse, poster_url) as (values
""" + ',\n'.join("  (%d, %d, %s)" % (i['chapter'], i['verse'], q(BASE + bgs[n % len(bgs)])) for n, i in enumerate(items)) + """
)
insert into reels (shlok_id, style, status, published_at, duration_s, poster_url)
select s.id, 'devotional', 'published', now(), 20, p.poster_url
from s join posters p using (chapter, verse);
"""
open(os.path.join(ROOT, 'supabase/seed.sql'), 'w', encoding='utf-8').write(sql)
print(len(items), 'shloks')
