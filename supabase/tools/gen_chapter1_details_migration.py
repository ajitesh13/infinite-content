#!/usr/bin/env python3
"""Generate the migration that adds titles, meanings, daily notes and backgrounds to chapter 1.

Reads content/chapter1_details.py. Run once from the repo root; the output is a new migration
(never edit an applied one): python3 supabase/tools/gen_chapter1_details_migration.py <timestamp>
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..', 'content'))
from chapter1_details import D

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
BG = 'https://zsauxjqrtdrjbpanlypq.supabase.co/storage/v1/object/public/reels/backgrounds/'
CREDIT = ('Sanskrit: moolam via Heritage IITK (public domain). Recitation: Swami Brahmananda, CC BY-SA 4.0, '
          'Heritage IITK. English meaning: AI-drafted paraphrase. Draft — pending editorial review')
files = {f.split('-')[2]: f for f in os.listdir(os.path.join(ROOT, 'assets/background')) if f.endswith('.jpg')}
q = lambda s: '$q$' + s + '$q$'
assert sorted(D) == list(range(1, 48))
vals = ',\n'.join('  (%d, %s, %s, %s, %s)' % (v, q(t), q(m), q(a), q(BG + files['%02d' % bg]))
                  for v, (t, m, a, bg) in sorted(D.items()))
sql = f"""-- GENERATED by supabase/tools/gen_chapter1_details_migration.py from content/chapter1_details.py. Do not edit by hand.
-- Chapter 1: English title, meaning and daily note (AI-drafted, pending review) plus a background per reel.
with d(verse, title, meaning, application, poster) as (values
{vals}
), s as (
  update shloks set title_english = d.title, english_meaning = d.meaning, application_english = d.application,
         translation_credit = {q(CREDIT)}
  from d where shloks.chapter = 1 and shloks.verse = d.verse
  returning shloks.id, d.poster
)
update reels set poster_url = s.poster from s where reels.shlok_id = s.id and reels.feed_mode = 'chapter';
"""
open(os.path.join(ROOT, f'supabase/migrations/{sys.argv[1]}_chapter1_details.sql'), 'w', encoding='utf-8').write(sql)
