#!/usr/bin/env python3
"""Generate one migration that adds a whole chapter in 'chapter' mode (used for chapter 2 onwards).

Inputs: content/chapter<N>.json (fetch_chapter.py) and content/chapter<N>_details.py (D = titles/notes for
verses with no existing shlok row, BG = background number per chapter reel).
 - Verses already in the daily mix keep their Sanskrit, title and note; they only gain Heritage meanings.
   Existing two-verse entries (verse_end) get both verses' translations joined and one reel with both audio files.
 - Every shlok row of the chapter gets one feed_mode='chapter' reel (skipped if it already has one).
Usage (repo root): python3 supabase/tools/gen_chapter_migration.py <chapter> <timestamp|--todo>
"""
import importlib, json, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from text_repairs import repair

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'content'))
ch = int(sys.argv[1])
rows = json.load(open(os.path.join(ROOT, f'content/chapter{ch}.json'), encoding='utf-8'))

# Verses already in the daily mix (content md headings): they keep their text; ranges swallow later verses.
existing, extras = set(), set()
for m in re.finditer(r'^### Bhagavad Gītā %d\.(\d+)(?:[–-](\d+))?' % ch,
                     open(os.path.join(ROOT, 'content/bhagavad-gita-daily-life.md'), encoding='utf-8').read(), re.M):
    a = int(m[1]); b = int(m[2]) if m[2] else a
    existing |= set(range(a, b + 1)); extras |= set(range(a + 1, b + 1))
all_v = {r['verse'] for r in rows}
need_details = sorted(all_v - existing)
need_bg = sorted(all_v - extras)
if sys.argv[2] == '--todo':
    print('need details (title, note):', need_details)
    print('need background for:', need_bg)
    sys.exit(0)
ts = sys.argv[2]
det = importlib.import_module(f'chapter{ch}_details')
assert sorted(det.D) == need_details, ('details mismatch', sorted(set(need_details) ^ set(det.D)))
assert set(need_bg) <= set(det.BG), ('missing backgrounds', sorted(set(need_bg) - set(det.BG)))
assert all(1 <= n <= 50 for n in det.BG.values())
STORAGE = 'https://zsauxjqrtdrjbpanlypq.supabase.co/storage/v1/object/public/reels/'
files = {f.split('-')[2]: f for f in os.listdir(os.path.join(ROOT, 'assets/background')) if f.endswith('.jpg')}
CREDIT = ('Sanskrit: moolam via Heritage IITK (public domain). Recitation: Swami Brahmananda, CC BY-SA 4.0, Heritage IITK. '
          'English: Swami Sivananda. Hindi: Swami Tejomayananda. Translations via Heritage IITK with permission. ')
CREDIT_AI = CREDIT + 'Title and daily note: AI-drafted. Draft — pending editorial review'
CREDIT_ED = CREDIT + 'Title and daily note: editorial draft. Draft — pending editorial review'
q = lambda s: '$q$' + s + '$q$'

def clean(s):
    lines = [l.strip() for l in s.split('\n') if l.strip()]
    lines[-1] = re.sub(r'\s*।।\s*%d\.\d+\s*।।$' % ch, '॥', lines[-1])
    return '\n'.join(lines)

by_v = {r['verse']: r for r in rows}
new_vals = ',\n'.join('  (%d, %s, %s, %s)' % (v, q(clean(by_v[v]['sanskrit'])), q(t), q(a)) for v, (t, a) in sorted(det.D.items()))
m_vals = ',\n'.join('  (%d, %s, %s, %s, %s)' % (r['verse'], q(repair(r['en'])), q(r['hi']), q(STORAGE + 'audio/' + r['audio']),
                    q(STORAGE + 'backgrounds/' + files['%02d' % det.BG[r['verse']]]) if r['verse'] in det.BG else 'null')
                    for r in rows)
d_list = ','.join(str(v) for v in sorted(det.D))
sql = f"""-- GENERATED by supabase/tools/gen_chapter_migration.py (chapter {ch}) from content/chapter{ch}.json. Do not edit by hand.
-- Chapter {ch} in chapter mode: Heritage IITK moolam, recitation, and translations used with permission.
-- Verses already in the daily mix keep their Sanskrit/title/note and gain the Heritage meanings.
create temp table m{ch}(verse int, en text, hi text, audio text, poster text);
insert into m{ch} values
{m_vals};

insert into shloks (chapter, verse, sanskrit, hindi_meaning, english_meaning, title_english, application_english, translation_credit, themes)
select {ch}, v.verse, v.sanskrit, null, null, v.title, v.application, {q(CREDIT_AI)}, '{{}}'::text[]
from (values
{new_vals}
) as v(verse, sanskrit, title, application)
on conflict (chapter, verse) do nothing;

update shloks s set
  english_meaning = (select string_agg(m.en, ' ' order by m.verse) from m{ch} m where m.verse between s.verse and coalesce(s.verse_end, s.verse)),
  hindi_meaning = (select string_agg(m.hi, ' ' order by m.verse) from m{ch} m where m.verse between s.verse and coalesce(s.verse_end, s.verse)),
  translation_credit = case when s.verse in ({d_list}) then {q(CREDIT_AI)} else {q(CREDIT_ED)} end
where s.chapter = {ch};

insert into reels (shlok_id, style, status, published_at, poster_url, audio_urls, feed_mode)
select s.id, 'devotional', 'published', now(),
       (select m.poster from m{ch} m where m.verse = s.verse),
       (select array_agg(m.audio order by m.verse) from m{ch} m where m.verse between s.verse and coalesce(s.verse_end, s.verse)),
       'chapter'
from shloks s
where s.chapter = {ch}
  and not exists (select 1 from reels r where r.shlok_id = s.id and r.feed_mode = 'chapter');

drop table m{ch};
"""
open(os.path.join(ROOT, f'supabase/migrations/{ts}_chapter{ch}.sql'), 'w', encoding='utf-8').write(sql)
print('ok', len(rows))
