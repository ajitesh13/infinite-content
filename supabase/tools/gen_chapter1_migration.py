#!/usr/bin/env python3
"""Generate the chapter-1 content migration from content/chapter1.json (see fetch_chapter1.py).

Sanskrit is copied verbatim; only whitespace is normalised and the trailing source verse-number
marker (।।1.N।।) is rendered as ॥ like the other seed verses. No meaning text is stored: the
modern-language translations on Heritage IITK are licensed for on-site reading only.
Run from the repo root: python3 supabase/tools/gen_chapter1_migration.py
"""
import json, os, re

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
STORAGE = 'https://zsauxjqrtdrjbpanlypq.supabase.co/storage/v1/object/public/reels/audio/'
CREDIT = ('Sanskrit: moolam via Heritage IITK (public domain). Recitation: Swami Brahmananda, CC BY-SA 4.0, '
          'Heritage IITK. Meaning not yet added. Draft — pending editorial review')

def clean(s):
    lines = [l.strip() for l in s.split('\n') if l.strip()]
    lines[-1] = re.sub(r'\s*।।\s*1\.\d+\s*।।$', '॥', lines[-1])
    return '\n'.join(lines)

q = lambda s: '$q$' + s + '$q$'
rows = [(d['verse'], clean(d['sanskrit']), STORAGE + d['audio'])
        for d in json.load(open(os.path.join(ROOT, 'content/chapter1.json'), encoding='utf-8'))]
assert [r[0] for r in rows] == list(range(1, 48))

vals = ',\n'.join('  (%d, %s, %s)' % (v, q(s), q(a)) for v, s, a in rows)
sql = f"""-- GENERATED by supabase/tools/gen_chapter1_migration.py from content/chapter1.json. Do not edit by hand.
-- Bhagavad Gita chapter 1 (47 verses): Sanskrit moolam + recitation only; backgrounds and meanings come later.
-- Reels are feed_mode 'chapter', so they only appear when a reader starts from chapter 1.
with v(verse, sanskrit, audio) as (values
{vals}
), s as (
  insert into shloks (chapter, verse, sanskrit, hindi_meaning, english_meaning, translation_credit, themes)
  select 1, verse, sanskrit, null, null, {q(CREDIT)}, '{{}}'::text[] from v
  on conflict (chapter, verse) do nothing
  returning id, verse
)
insert into reels (shlok_id, style, status, published_at, poster_url, audio_urls, feed_mode)
select s.id, 'devotional', 'published', now(), null, array[v.audio]::text[], 'chapter'
from s join v using (verse);
"""
open(os.path.join(ROOT, 'supabase/migrations/20261104000100_chapter1_content.sql'), 'w', encoding='utf-8').write(sql)
print(len(rows), 'verses')
